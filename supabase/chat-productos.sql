-- Solo las RPC públicas del módulo son invocables; helpers privados cerrados.
do $$ declare f record; begin
 for f in select p.oid::regprocedure as signature,p.proname from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname like 'mega_chat_%' loop
  execute format('revoke all on function %s from public,anon,authenticated',f.signature);
  if f.proname not in ('mega_chat_access','mega_chat_cipher') then execute format('grant execute on function %s to authenticated',f.signature); end if;
 end loop;
end $$;
-- Los respaldos locales conservan también conversaciones, decisiones y fotos cifradas.
do $$ begin
 if to_regprocedure('public.mega_audit_backup_snapshot_before_chat(uuid)') is null then
  alter function public.mega_audit_backup_snapshot(uuid) rename to mega_audit_backup_snapshot_before_chat;
 end if;
end $$;
create or replace function public.mega_audit_backup_snapshot(p_workspace_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v jsonb; extra jsonb; authors jsonb;
begin
 v:=public.mega_audit_backup_snapshot_before_chat(p_workspace_id);
 select jsonb_build_object(
  'mega_chat_messages',coalesce((select jsonb_agg(to_jsonb(r) order by r.seq) from public.mega_chat_messages r where r.workspace_id=p_workspace_id),'[]'::jsonb),
  'mega_chat_cases',coalesce((select jsonb_agg(to_jsonb(r) order by r.id) from public.mega_chat_cases r where r.workspace_id=p_workspace_id),'[]'::jsonb),
  'mega_chat_followers',coalesce((select jsonb_agg(to_jsonb(r)) from public.mega_chat_followers r where r.workspace_id=p_workspace_id),'[]'::jsonb),
  'mega_chat_case_events',coalesce((select jsonb_agg(to_jsonb(r) order by r.case_id,r.revision) from public.mega_chat_case_events r where r.workspace_id=p_workspace_id),'[]'::jsonb),
  'mega_chat_products',coalesce((select jsonb_agg(to_jsonb(r)) from public.mega_chat_products r where r.workspace_id=p_workspace_id),'[]'::jsonb),
  'mega_chat_product_events',coalesce((select jsonb_agg(to_jsonb(r)) from public.mega_chat_product_events r where r.workspace_id=p_workspace_id),'[]'::jsonb),
  'mega_chat_notifications',coalesce((select jsonb_agg(to_jsonb(r)) from public.mega_chat_notifications r where r.workspace_id=p_workspace_id),'[]'::jsonb),
  'mega_chat_files',coalesce((select jsonb_agg(to_jsonb(r)) from public.mega_chat_files r where r.workspace_id=p_workspace_id),'[]'::jsonb)
 ) into extra;
 v:=jsonb_set(v,'{tables}',(v->'tables')||extra);
 v:=jsonb_set(v,'{objects}',(v->'objects')||coalesce((select jsonb_agg(jsonb_build_object('name',o.name,'size',o.metadata->>'size','updated_at',o.updated_at,'bucket','mega-chat-images') order by o.name) from storage.objects o join public.mega_chat_files f on f.path=o.name where o.bucket_id='mega-chat-images' and f.workspace_id=p_workspace_id),'[]'::jsonb));
 select coalesce(jsonb_agg(jsonb_build_object('user_id',u.id,'username',split_part(u.email,'@',1)) order by u.id),'[]'::jsonb) into authors from auth.users u where exists(select 1 from jsonb_array_elements(v->'authors') a where a->>'user_id'=u.id::text) or exists(select 1 from public.mega_chat_messages m where m.workspace_id=p_workspace_id and m.created_by=u.id) or exists(select 1 from public.mega_chat_case_events e where e.workspace_id=p_workspace_id and e.changed_by=u.id) or exists(select 1 from public.mega_chat_product_events e where e.workspace_id=p_workspace_id and e.updated_by=u.id) or exists(select 1 from public.mega_chat_files f where f.workspace_id=p_workspace_id and f.uploaded_by=u.id);
 return jsonb_set(v,'{authors}',authors);
end $$;
