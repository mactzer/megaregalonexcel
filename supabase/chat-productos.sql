create or replace function public.mega_chat_file_access(p_name text,p_write boolean default false)
returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.mega_chat_files f where f.path=p_name and public.mega_audit_is_member(f.workspace_id) and (not p_write or f.uploaded_by=auth.uid() and not f.attached));
$$;
