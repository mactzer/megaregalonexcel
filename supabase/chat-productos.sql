-- Chat cifrado de MegaControl. Aditivo; no modifica salidas ni documentos originales.
begin;
create table if not exists public.mega_chat_messages (
 id uuid primary key, seq bigint generated by default as identity unique,
 workspace_id uuid not null references public.mega_audit_workspace(id),
 created_by uuid not null references auth.users(id), created_at timestamptz not null default now(),
 kind text not null check(kind in ('text','sticker','image','product','case')),
 encrypted_body text not null check(length(encrypted_body) between 32 and 32768),
 parent_id uuid, case_id uuid, unique(workspace_id,id),
 foreign key(workspace_id,parent_id) references public.mega_chat_messages(workspace_id,id)
);
create index if not exists mega_chat_messages_page on public.mega_chat_messages(workspace_id,seq desc);
create index if not exists mega_chat_messages_author on public.mega_chat_messages(workspace_id,created_by,created_at desc);
create index if not exists mega_chat_messages_thread on public.mega_chat_messages(workspace_id,parent_id,seq);
create table if not exists public.mega_chat_cases (
 id uuid primary key references public.mega_chat_messages(id) deferrable initially deferred,
 workspace_id uuid not null references public.mega_audit_workspace(id), product_tag text not null check(product_tag ~ '^[a-f0-9]{64}$'),
 status text not null default 'pending' check(status in ('pending','in_progress','resolved','unidentifiable')),
 assigned_to uuid references auth.users(id), revision integer not null default 0,
 encrypted_resolution text, updated_by uuid not null references auth.users(id), updated_at timestamptz not null default now(),
 unique(workspace_id,id)
);
create unique index if not exists mega_chat_case_open on public.mega_chat_cases(workspace_id,product_tag) where status in ('pending','in_progress');
create index if not exists mega_chat_cases_page on public.mega_chat_cases(workspace_id,status,updated_at desc);
create table if not exists public.mega_chat_followers (
 workspace_id uuid not null, case_id uuid not null, user_id uuid not null references auth.users(id),
 primary key(workspace_id,case_id,user_id), foreign key(workspace_id,case_id) references public.mega_chat_cases(workspace_id,id)
);
create table if not exists public.mega_chat_case_events (
 workspace_id uuid not null, case_id uuid not null, revision integer not null,
 status text not null, assigned_to uuid references auth.users(id), encrypted_resolution text not null,
 changed_by uuid not null references auth.users(id), created_at timestamptz not null default now(),
 primary key(workspace_id,case_id,revision), foreign key(workspace_id,case_id) references public.mega_chat_cases(workspace_id,id)
);
create table if not exists public.mega_chat_products (
 workspace_id uuid not null references public.mega_audit_workspace(id), product_tag text not null check(product_tag ~ '^[a-f0-9]{64}$'),
 encrypted_product text not null, version integer not null, updated_by uuid not null references auth.users(id), updated_at timestamptz not null default now(),
 primary key(workspace_id,product_tag)
);
create table if not exists public.mega_chat_product_events (
 workspace_id uuid not null, product_tag text not null, version integer not null,
 encrypted_product text not null, updated_by uuid not null references auth.users(id), updated_at timestamptz not null,
 primary key(workspace_id,product_tag,version), foreign key(workspace_id,product_tag) references public.mega_chat_products(workspace_id,product_tag)
);
create table if not exists public.mega_chat_notifications (
 id bigint generated by default as identity primary key, workspace_id uuid not null references public.mega_audit_workspace(id),
 user_id uuid not null references auth.users(id), message_id uuid not null references public.mega_chat_messages(id),
 kind text not null check(kind in ('message','reply','mention','case','assigned','resolved','status')),
 revision integer not null default 0, created_at timestamptz not null default now(), read_at timestamptz,
 unique(user_id,message_id,kind,revision)
);
create index if not exists mega_chat_notifications_unread on public.mega_chat_notifications(workspace_id,user_id,id desc) where read_at is null;
create table if not exists public.mega_chat_files (
 id uuid primary key, workspace_id uuid not null references public.mega_audit_workspace(id),
 uploaded_by uuid not null references auth.users(id), size integer not null check(size between 29 and 163904),
 created_at timestamptz not null default now(), attached boolean not null default false,
 path text not null unique check(path=workspace_id::text||'/'||uploaded_by::text||'/'||id::text||'/image.bin')
);
-- Mutaciones únicamente mediante RPC. Los guardas restrictivos resisten políticas amplias ajenas.
do $$ declare t text; begin
 foreach t in array array['mega_chat_messages','mega_chat_cases','mega_chat_followers','mega_chat_case_events','mega_chat_products','mega_chat_product_events','mega_chat_files','mega_chat_notifications'] loop
  execute format('alter table public.%I enable row level security',t);
  execute format('revoke all on public.%I from public,anon,authenticated',t);
  execute format('grant select on public.%I to authenticated',t);
  execute format('drop policy if exists chat_read on public.%I',t);
  execute format('create policy chat_read on public.%I for select to authenticated using(public.mega_audit_is_member(workspace_id))',t);
  execute format('drop policy if exists chat_member_guard on public.%I',t);
  execute format('create policy chat_member_guard on public.%I as restrictive for all to authenticated using(public.mega_audit_is_member(workspace_id)) with check(false)',t);
  execute format('drop policy if exists chat_anon_guard on public.%I',t);
  execute format('create policy chat_anon_guard on public.%I as restrictive for all to anon using(false) with check(false)',t);
  execute format('drop policy if exists chat_update_guard on public.%I',t);
  execute format('create policy chat_update_guard on public.%I as restrictive for update to authenticated using(false) with check(false)',t);
  execute format('drop policy if exists chat_delete_guard on public.%I',t);
  execute format('create policy chat_delete_guard on public.%I as restrictive for delete to authenticated using(false)',t);
 end loop;
end $$;
drop policy if exists chat_private_notifications on public.mega_chat_notifications;
create policy chat_private_notifications on public.mega_chat_notifications as restrictive for select to authenticated using(user_id=auth.uid());

create or replace function public.mega_chat_access(p_workspace_id uuid,p_admin boolean default false)
returns uuid language plpgsql security definer set search_path='' as $$
declare u uuid:=auth.uid(); begin
 if u is null then raise exception 'Inicia sesión.' using errcode='42501'; end if;
 perform 1 from public.mega_audit_members m where m.workspace_id=p_workspace_id and m.user_id=u and (not p_admin or m.role='admin') for share;
 if not found then raise exception 'Tu cuenta no tiene permisos para esta operación.' using errcode='42501'; end if;
 return u;
end $$;
create or replace function public.mega_chat_cipher(p_value text)
returns boolean language sql immutable set search_path='' as $$
 select p_value is not null and length(p_value) between 32 and 32768 and length(p_value)%4=0 and p_value ~ '^([A-Za-z0-9+/]{4})*([A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$';
$$;
create or replace function public.mega_chat_members(p_workspace_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$ begin
 perform public.mega_chat_access(p_workspace_id);
 return coalesce((select jsonb_agg(jsonb_build_object('id',u.id,'username',split_part(u.email,'@',1),'role',coalesce(m.role,'former')) order by u.email) from auth.users u left join public.mega_audit_members m on m.user_id=u.id and m.workspace_id=p_workspace_id where m.user_id is not null or exists(select 1 from public.mega_chat_messages h where h.workspace_id=p_workspace_id and h.created_by=u.id) or exists(select 1 from public.mega_chat_case_events e where e.workspace_id=p_workspace_id and e.changed_by=u.id)),'[]'::jsonb);
end $$;
create or replace function public.mega_chat_send(p_workspace_id uuid,p_id uuid,p_kind text,p_body text,p_parent uuid default null,p_mentions uuid[] default '{}')
returns jsonb language plpgsql security definer set search_path='' as $$
declare u uuid:=public.mega_chat_access(p_workspace_id); r public.mega_chat_messages%rowtype; parent public.mega_chat_messages%rowtype;
begin
 if p_id is null or p_kind not in ('text','sticker','image','product') or not public.mega_chat_cipher(p_body) or coalesce(cardinality(p_mentions),0)>20 then raise exception 'Mensaje inválido.' using errcode='22023'; end if;
 -- Serializa reintentos y asignación de secuencia: no quedan mensajes con secuencia menor confirmados tarde.
 perform 1 from public.mega_audit_workspace where id=p_workspace_id for update;
 select * into r from public.mega_chat_messages where id=p_id;
 if found then
  if r.workspace_id<>p_workspace_id or r.created_by<>u or r.kind<>p_kind or r.encrypted_body<>p_body or r.parent_id is distinct from p_parent then raise exception 'El identificador ya se usó.' using errcode='23505'; end if;
  return to_jsonb(r);
 end if;
 if (select count(*) from public.mega_chat_messages where workspace_id=p_workspace_id and created_by=u and created_at>now()-interval '1 minute')>=60 then raise exception 'Espera un momento antes de enviar más mensajes.' using errcode='54000'; end if;
 if p_parent is not null then
  select * into parent from public.mega_chat_messages where workspace_id=p_workspace_id and id=p_parent;
  if not found then raise exception 'La conversación original no existe.' using errcode='22023'; end if;
 end if;
 if p_kind='image' then
  perform 1 from public.mega_chat_files f join storage.objects o on o.bucket_id='mega-chat-images' and o.name=f.path
    where f.id=p_id and f.workspace_id=p_workspace_id and f.uploaded_by=u and coalesce((o.metadata->>'size')::bigint,0)=f.size;
  if not found then raise exception 'La imagen aún no se ha guardado por completo.' using errcode='22023'; end if;
 end if;
 insert into public.mega_chat_messages(id,workspace_id,created_by,kind,encrypted_body,parent_id,case_id)
 values(p_id,p_workspace_id,u,p_kind,p_body,p_parent,case when parent.kind='case' then parent.id else parent.case_id end) returning * into r;
 if p_kind='image' then update public.mega_chat_files set attached=true where id=p_id; end if;
 if r.case_id is not null then insert into public.mega_chat_followers values(p_workspace_id,r.case_id,u) on conflict do nothing; end if;
 insert into public.mega_chat_notifications(workspace_id,user_id,message_id,kind)
 select p_workspace_id,m.user_id,r.id,case when m.user_id=any(coalesce(p_mentions,'{}')) then 'mention' when m.user_id=parent.created_by or exists(select 1 from public.mega_chat_followers f where f.case_id=r.case_id and f.user_id=m.user_id) then 'reply' else 'message' end
 from public.mega_audit_members m where m.workspace_id=p_workspace_id and m.user_id<>u on conflict do nothing;
 return to_jsonb(r);
end $$;
create or replace function public.mega_chat_case_open(p_workspace_id uuid,p_id uuid,p_tag text,p_body text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare u uuid:=public.mega_chat_access(p_workspace_id); c public.mega_chat_cases%rowtype; r public.mega_chat_messages%rowtype;
begin
 if p_id is null or p_tag is null or p_tag !~ '^[a-f0-9]{64}$' or not public.mega_chat_cipher(p_body) then raise exception 'Consulta inválida.' using errcode='22023'; end if;
 perform 1 from public.mega_audit_workspace where id=p_workspace_id for update;
 select * into c from public.mega_chat_cases where workspace_id=p_workspace_id and product_tag=p_tag and (status in ('pending','in_progress') or id=p_id) order by updated_at desc limit 1;
 if not found then
  insert into public.mega_chat_messages(id,workspace_id,created_by,kind,encrypted_body,case_id) values(p_id,p_workspace_id,u,'case',p_body,p_id) returning * into r;
  insert into public.mega_chat_cases(id,workspace_id,product_tag,updated_by) values(p_id,p_workspace_id,p_tag,u) returning * into c;
  insert into public.mega_chat_notifications(workspace_id,user_id,message_id,kind) select p_workspace_id,m.user_id,p_id,'case' from public.mega_audit_members m where m.workspace_id=p_workspace_id and m.user_id<>u on conflict do nothing;
 end if;
 insert into public.mega_chat_followers values(p_workspace_id,c.id,u) on conflict do nothing;
 return to_jsonb(c);
end $$;
create or replace function public.mega_chat_case_follow(p_workspace_id uuid,p_id uuid)
returns boolean language plpgsql security definer set search_path='' as $$
declare u uuid:=public.mega_chat_access(p_workspace_id); begin
 if not exists(select 1 from public.mega_chat_cases where workspace_id=p_workspace_id and id=p_id) then raise exception 'Solicitud inexistente.'; end if;
 insert into public.mega_chat_followers values(p_workspace_id,p_id,u) on conflict do nothing; return true;
end $$;
create or replace function public.mega_chat_case_update(p_workspace_id uuid,p_id uuid,p_expected integer,p_status text,p_assigned uuid,p_resolution text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare u uuid:=public.mega_chat_access(p_workspace_id,true); c public.mega_chat_cases%rowtype;
begin
 if p_status is null or p_status not in ('pending','in_progress','resolved','unidentifiable') or p_expected is null or p_expected<0 or not public.mega_chat_cipher(p_resolution) then raise exception 'Estado o explicación inválidos.' using errcode='22023'; end if;
 if p_assigned is not null and not exists(select 1 from public.mega_audit_members where workspace_id=p_workspace_id and user_id=p_assigned and role='admin') then raise exception 'Asigna la solicitud a un administrador autorizado.' using errcode='42501'; end if;
 perform 1 from public.mega_audit_workspace where id=p_workspace_id for update;
 select * into c from public.mega_chat_cases where workspace_id=p_workspace_id and id=p_id for update;
 if not found then raise exception 'Solicitud inexistente.' using errcode='22023'; end if;
 if c.revision=p_expected+1 and c.encrypted_resolution=p_resolution and c.status=p_status and c.assigned_to is not distinct from p_assigned and c.updated_by=u then return to_jsonb(c); end if;
 if c.revision<>p_expected then raise exception 'Otro administrador actualizó el caso. Vuelve a abrirlo.' using errcode='40001'; end if;
 update public.mega_chat_cases set status=p_status,assigned_to=p_assigned,encrypted_resolution=p_resolution,revision=revision+1,updated_by=u,updated_at=clock_timestamp() where id=p_id returning * into c;
 insert into public.mega_chat_case_events values(p_workspace_id,p_id,c.revision,c.status,c.assigned_to,p_resolution,u,c.updated_at);
 insert into public.mega_chat_notifications(workspace_id,user_id,message_id,kind,revision)
 select p_workspace_id,m.user_id,p_id,case when m.user_id=p_assigned then 'assigned' when p_status='resolved' then 'resolved' else 'status' end,c.revision from public.mega_audit_members m where m.workspace_id=p_workspace_id and m.user_id<>u and (m.user_id=p_assigned or exists(select 1 from public.mega_chat_followers f where f.case_id=p_id and f.user_id=m.user_id)) on conflict do nothing;
 return to_jsonb(c);
end $$;
create or replace function public.mega_chat_product_put(p_workspace_id uuid,p_tag text,p_expected integer,p_product text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare u uuid:=public.mega_chat_access(p_workspace_id,true); r public.mega_chat_products%rowtype;
begin
 if p_tag is null or p_tag !~ '^[a-f0-9]{64}$' or p_expected is null or p_expected<0 or not public.mega_chat_cipher(p_product) then raise exception 'Producto inválido.' using errcode='22023'; end if;
 perform 1 from public.mega_audit_workspace where id=p_workspace_id for update;
 select * into r from public.mega_chat_products where workspace_id=p_workspace_id and product_tag=p_tag for update;
 if found then
  if r.version=p_expected+1 and r.encrypted_product=p_product and r.updated_by=u then return to_jsonb(r); end if;
  if r.version<>p_expected then raise exception 'El producto cambió. Consulta de nuevo.' using errcode='40001'; end if;
  update public.mega_chat_products set version=version+1,encrypted_product=p_product,updated_by=u,updated_at=clock_timestamp() where workspace_id=p_workspace_id and product_tag=p_tag returning * into r;
 else
  if p_expected<>0 then raise exception 'El producto cambió.' using errcode='40001'; end if;
  insert into public.mega_chat_products values(p_workspace_id,p_tag,p_product,1,u,clock_timestamp()) returning * into r;
 end if;
 insert into public.mega_chat_product_events values(r.workspace_id,r.product_tag,r.version,r.encrypted_product,r.updated_by,r.updated_at);
 return to_jsonb(r);
end $$;
create or replace function public.mega_chat_read(p_workspace_id uuid,p_through bigint,p_only boolean default false)
returns boolean language plpgsql security definer set search_path='' as $$
declare u uuid:=public.mega_chat_access(p_workspace_id); begin
 update public.mega_chat_notifications set read_at=clock_timestamp() where workspace_id=p_workspace_id and user_id=u and read_at is null and (case when p_only then id=p_through else id<=p_through end);
 return true;
end $$;
create or replace function public.mega_chat_image_prepare(p_workspace_id uuid,p_id uuid,p_size integer)
returns jsonb language plpgsql security definer set search_path='' as $$
declare u uuid:=public.mega_chat_access(p_workspace_id); f public.mega_chat_files%rowtype;
begin
 if p_id is null or p_size is null or p_size not between 29 and 163904 then raise exception 'Imagen demasiado grande.' using errcode='22023'; end if;
 perform 1 from public.mega_audit_workspace where id=p_workspace_id for update;
 select * into f from public.mega_chat_files where id=p_id;
 if found then
  if f.workspace_id<>p_workspace_id or f.uploaded_by<>u or f.size<>p_size then raise exception 'Imagen distinta para el mismo envío.' using errcode='23505'; end if;
  return to_jsonb(f);
 end if;
 -- Reserva hasta 80 MB a tamaño máximo por archivo, incluso si se declara un tamaño menor.
 -- Protege el plan Free sin borrar conversaciones ni permitir eludir la cuota con reservas pequeñas.
 if (select count(*) from public.mega_chat_files where workspace_id=p_workspace_id)*163904+163904>83886080 then raise exception 'El chat alcanzó su límite de 80 MB de fotos. Los mensajes siguen disponibles.' using errcode='54000'; end if;
 insert into public.mega_chat_files(id,workspace_id,uploaded_by,size,path) values(p_id,p_workspace_id,u,p_size,p_workspace_id::text||'/'||u::text||'/'||p_id::text||'/image.bin') returning * into f;
 return to_jsonb(f);
end $$;
