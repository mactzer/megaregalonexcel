create policy chat_image_insert on storage.objects for insert to authenticated with check(bucket_id='mega-chat-images' and public.mega_chat_file_access(name,true));
drop policy if exists chat_image_insert_guard on storage.objects;
create policy chat_image_insert_guard on storage.objects as restrictive for insert to anon,authenticated with check(bucket_id<>'mega-chat-images' or public.mega_chat_file_access(name,true));
drop policy if exists chat_image_update_guard on storage.objects;
create policy chat_image_update_guard on storage.objects as restrictive for update to anon,authenticated using(bucket_id<>'mega-chat-images') with check(bucket_id<>'mega-chat-images');
